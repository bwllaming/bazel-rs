#!/usr/bin/env python3
"""Regenerate src/option_metadata.rs from genuine Bazel 9.3.0 `help flags-as-proto`.

Usage:
  extract_option_metadata.py --bazel /path/to/bazel-9.3.0 --scratch DIR > src/option_metadata.rs
  extract_option_metadata.py --from-base64 FLAGS.b64 > src/option_metadata.rs

The same pinned capture as scripts/extract_command_options.py (binary and
base64 output SHA-256 checked there). Kept per option, for `help` (the
command membership bit order) and `canonicalize-flags`
(OptionsParserImpl.asCanonicalizedList): the commands that register it (and
`startup`), abbreviation, boolean syntax, whether it may be used multiple
times, converter and expansion.
"""

import argparse
import base64
import hashlib
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import extract_command_options as base  # noqa: E402

COMMANDS = ['aquery', 'build', 'canonicalize-flags', 'clean', 'config', 'coverage', 'cquery',
            'dump', 'fetch', 'help', 'info', 'license', 'mobile-install', 'mod', 'print_action',
            'query', 'run', 'shutdown', 'test', 'vendor', 'version', 'startup']


def decode(encoded):
    flags = []
    for number, value in base.fields(base64.b64decode(encoded.strip(), validate=True)):
        if number != 1:
            raise ValueError('not a FlagCollection')
        flag = dict(commands=[], negative=False, abbrev='', multiple=False, category='',
                    default=None, expansions=[], converter='', enums=[])
        for field, item in base.fields(value):
            if field == 1:
                flag['name'] = item.decode()
            elif field == 2:
                flag['negative'] = bool(item)
            elif field == 4:
                flag['commands'].append(item.decode())
            elif field == 5:
                flag['abbrev'] = item.decode()
            elif field == 6:
                flag['multiple'] = bool(item)
            elif field == 9:
                flag['category'] = item.decode()
            elif field == 13:
                flag['default'] = item.decode()
            elif field == 14:
                flag['expansions'].append(item.decode())
            elif field == 15:
                flag['converter'] = item.decode()
            elif field == 16:
                flag['enums'].append(item.decode())
        flags.append(flag)
    return flags


def render(flags, digest):
    rows = []
    for flag in sorted(flags, key=lambda f: f['name']):
        mask = 0
        for command in flag['commands']:
            mask |= 1 << COMMANDS.index(command)
        abbrev = repr(flag['abbrev']) if flag['abbrev'] else "'\\0'"
        rows.append('    O {{ name: {}, abbrev: {}, boolean: {}, multiple: {}, converter: {}, '
                    'expansion: &[{}], commands: {:#x} }},'
                    .format(base.rust_string(flag['name']), abbrev,
                            'true' if flag['negative'] else 'false',
                            'true' if flag['multiple'] else 'false',
                            base.rust_string(flag['converter']),
                            ', '.join(base.rust_string(e) for e in flag['expansions']), mask))
    out = [
        '//! Generated by scripts/extract_option_metadata.py from genuine Bazel 9.3.0',
        f'//! (sha256 {base.REFERENCE_SHA256}) `help flags-as-proto`',
        f'//! (base64 sha256 {digest}); do not edit.',
        '//! Every non-INTERNAL option (src/main/protobuf/bazel_flags.proto FlagInfo) without its',
        '//! help text; `commands` is a bit set over [`COMMANDS`].',
        '',
        '/// One option (FlagInfo).',
        '#[derive(Clone, Copy, Debug)]',
        'pub(crate) struct O {',
        '    pub name: &\'static str,',
        '    pub abbrev: char,',
        '    /// OptionDefinition.usesBooleanValueSyntax (`--[no]name`).',
        '    pub boolean: bool,',
        '    pub multiple: bool,',
        '    /// The converter class\'s simple name without `Converter`.',
        '    pub converter: &\'static str,',
        '    pub expansion: &\'static [&\'static str],',
        '    pub commands: u32,',
        '}',
        '',
        '/// The bit order of [`O::commands`].',
        '#[rustfmt::skip]',
        'pub(crate) const COMMANDS: &[&str] = &[{}];'.format(
            ', '.join(base.rust_string(command) for command in COMMANDS)),
        '',
        '#[rustfmt::skip]',
        'pub(crate) const OPTIONS: &[O] = &[',
        *rows,
        '];',
    ]
    return '\n'.join(out) + '\n'


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    source = parser.add_mutually_exclusive_group(required=True)
    source.add_argument('--bazel')
    source.add_argument('--from-base64')
    parser.add_argument('--scratch', default='/tmp/opencode')
    args = parser.parse_args()
    if args.bazel:
        encoded = base.capture(args.bazel, args.scratch)
    else:
        with open(args.from_base64) as stream:
            encoded = stream.read()
    digest = hashlib.sha256(encoded.strip().encode()).hexdigest()
    if digest != base.FLAGS_SHA256:
        raise SystemExit(f'refusing to generate: base64 sha256 {digest}, not {base.FLAGS_SHA256}')
    sys.stdout.write(render(decode(encoded), digest))


if __name__ == '__main__':
    main()
