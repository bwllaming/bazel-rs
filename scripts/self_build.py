class CacheServer:
    """A minimal HTTP/1.1 remote cache (Bazel's /ac/ and /cas/ protocol) on loopback."""

    def __init__(self, root: Path):
        root.mkdir(parents=True, exist_ok=True)
        stats: collections.Counter = collections.Counter()
        lock = threading.Lock()

        class Handler(http.server.BaseHTTPRequestHandler):
            protocol_version = "HTTP/1.1"
            disable_nagle_algorithm = True

            def log_message(self, *args):
                pass

            def entry(self) -> tuple[str, Path]:
                kind = self.path.strip("/").split("/", 1)[0]
                return kind, root / self.path.strip("/").replace("/", "_")

            def empty(self, code: int) -> None:
                self.send_response(code)
                self.send_header("Content-Length", "0")
                self.end_headers()

            def do_GET(self):
                kind, path = self.entry()
                try:
                    data = path.read_bytes()
                except FileNotFoundError:
                    with lock:
                        stats[f"get_miss_{kind}"] += 1
                    return self.empty(404)
                with lock:
                    stats[f"get_hit_{kind}"] += 1
                self.send_response(200)
                self.send_header("Content-Length", str(len(data)))
                self.end_headers()
                self.wfile.write(data)

            def do_HEAD(self):
                self.empty(200 if self.entry()[1].exists() else 404)

            def do_PUT(self):
                kind, path = self.entry()
                data = self.rfile.read(int(self.headers.get("Content-Length", "0")))
                tmp = path.with_name(path.name + f".{threading.get_ident()}.tmp")
                tmp.write_bytes(data)
                tmp.replace(path)
                with lock:
                    stats[f"put_{kind}"] += 1
                self.empty(200)

        self.stats = stats
        self.server = http.server.ThreadingHTTPServer(("127.0.0.1", 0), Handler)
        self.url = f"http://127.0.0.1:{self.server.server_address[1]}"
        self.thread = threading.Thread(target=self.server.serve_forever, daemon=True)

    def __enter__(self) -> "CacheServer":
        self.thread.start()
        return self

    def __exit__(self, *exc) -> None:
        self.server.shutdown()
        self.server.server_close()

    def take_stats(self) -> dict[str, int]:
        snapshot = dict(sorted(self.stats.items()))
        self.stats.clear()
        return snapshot


def compare(genuine: str, bazel_rs: str, work: Path, extra: list[str]) -> list[dict]:
    rows = []
    for order in (("genuine", "bazel-rs"), ("bazel-rs", "genuine")):
        name = "-then-".join(order)
        with CacheServer(work / name / "remote-cache") as cache:
            for step, who in enumerate(order):
                binary = genuine if who == "genuine" else bazel_rs
                bazel = Bazel.detect(binary, work / name / f"{who}-state")
                run = bazel.run(
                    "build", f"--remote_cache={cache.url}", *extra, TARGET
                )
                counts = run.processes()
                hits = counts.get("remote cache hit", 0)
                rows.append(
                    {
                        "round": name,
                        "build": who,
                        "role": "fill" if step == 0 else "read",
                        "seconds": round(run.elapsed(), 1),
                        "processes": counts.get("total", 0),
                        "remote_hits": hits,
                        "summary": counts,
                        "cache": cache.take_stats(),
                    }
                )
                print(rows[-1], flush=True)
    return rows


def report(rows: list[dict]) -> str:
    out = [
        "| round | build | role | seconds | processes | remote cache hits | cache traffic |",
        "|---|---|---|---:|---:|---:|---|",
    ]
    for r in rows:
        traffic = ", ".join(f"{k} {v}" for k, v in r["cache"].items())
        out.append(
            f"| {r['round']} | {r['build']} | {r['role']} | {r['seconds']} | "
            f"{r['processes']} | {r['remote_hits']} | {traffic} |"
        )
    return "\n".join(out)


