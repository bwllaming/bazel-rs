# Running Bazel


@dataclasses.dataclass
class Bazel:
    """A Bazel-compatible binary with its private state directory."""

    binary: str
    state: Path
    genuine: bool

    @classmethod
    def detect(cls, binary: str, state: Path) -> "Bazel":
        version = subprocess.run(
            [binary, "--version"], capture_output=True, text=True, check=True
        ).stdout
        return cls(binary, state, not version.startswith("bazel-rs"))

    def startup(self) -> list[str]:
        # The workspace .bazelrc only; no system or user rc files.
        rc = ["--nosystem_rc", "--nohome_rc"]
        if self.genuine:
            return ["--batch", f"--output_user_root={self.state}", *rc]
        return [f"--cache-dir={self.state}", *rc]

    def run(self, *args: str, check: bool = True) -> "Run":
        argv = [self.binary, *self.startup(), *args]
        print("+ " + " ".join(argv), file=sys.stderr, flush=True)
        start = time.monotonic()
        proc = subprocess.run(argv, cwd=ROOT, text=True, capture_output=True)
        run = Run(proc.returncode, proc.stdout, proc.stderr, time.monotonic() - start)
        if check and proc.returncode != 0:
            raise SelfBuildError(
                f"exit {proc.returncode}: {' '.join(argv)}\n{tail(proc.stderr)}"
            )
        return run


@dataclasses.dataclass
class Run:
    returncode: int
    stdout: str
    stderr: str
    seconds: float

    def processes(self) -> dict[str, int]:
        """The last `INFO: N processes: ...` summary as {kind: count, "total": N}."""
        matches = PROCESSES_RE.findall(self.stderr)
        if not matches:
            return {}
        total, parts = matches[-1]
        counts = {"total": int(total)}
        for part in parts.split(", "):
            count, _, kind = part.partition(" ")
            if count.isdigit():
                counts[kind] = int(count)
        return counts

    def elapsed(self) -> float:
        match = ELAPSED_RE.findall(self.stderr)
        return float(match[-1]) if match else self.seconds


def tail(text: str, lines: int = 40) -> str:
    return "\n".join(text.strip().splitlines()[-lines:])


def built_binary(stderr: str) -> Path:
    """The `Target //:bazel-rs up-to-date:` path (relative: to the workspace)."""
    lines = stderr.splitlines()
    for i, line in enumerate(lines):
        if line.startswith(f"Target {TARGET} up-to-date") and i + 1 < len(lines):
            path = Path(lines[i + 1].strip())
            return path if path.is_absolute() else ROOT / path
    raise SelfBuildError(f"no `Target {TARGET} up-to-date` in the build output")


def cargo_version() -> str:
    import tomllib

    return tomllib.loads((ROOT / "Cargo.toml").read_text())["package"]["version"]


def load_release():
    spec = importlib.util.spec_from_file_location("release", ROOT / "scripts" / "release.py")
    module = importlib.util.module_from_spec(spec)
    sys.modules["release"] = module  # dataclasses look their module up
    spec.loader.exec_module(module)
    return module


# --------------------------------------------------------------------------
# check


def check(bazel: Bazel, scratch: Path, test: bool, extra: list[str]) -> None:
    build = bazel.run("build", *extra, TARGET)
    print(f"build {TARGET}: {build.elapsed():.1f}s, {build.processes()}")
    binary = built_binary(build.stderr)
    release = load_release()
    shutil.rmtree(scratch, ignore_errors=True)
    scratch.mkdir(parents=True)
    copy = scratch / "bazel-rs"
    shutil.copyfile(binary, copy)
    copy.chmod(0o755)
    compat = release.smoke_test(release.run_command, copy, cargo_version(), scratch / "smoke")
    print(f"smoke test of the Bazel-built bazel-rs: ok (compatibility target {compat})")
    if test:
        result = bazel.run("test", *extra, "//...", check=False)
        print(tail(result.stdout, 25))
        if result.returncode != 0:
            raise SelfBuildError(f"`test //...` failed (exit {result.returncode})")
        print(f"test //...: {result.elapsed():.1f}s")


