#!/usr/bin/env python3
"""Build bazel-rs with Bazel (rules_rust), the dogfood check (docs/SELF_BUILD.md).

    scripts/self_build.py check [--bazel BIN] [--state-dir DIR] [--no-test]
    scripts/self_build.py compare --genuine BIN [--bazel-rs BIN] --work-dir DIR
    scripts/self_build.py bazelignore [--check]

Cargo stays the primary build; MODULE.bazel and BUILD.bazel build the same
crate with rules_rust and crate_universe.

`check` builds //:bazel-rs with BIN (default: `bazel-rs` on PATH; genuine
Bazel works too), smoke-tests the result with scripts/release.py's offline
smoke test and runs `test //...`. bazel-rs keeps its cache in --state-dir
(`--cache-dir`); genuine Bazel its output user root (`--batch`).

`compare` builds //:bazel-rs four times from cold local state against a
private HTTP/1.1 remote cache started by this script: genuine Bazel filling
an empty cache, then bazel-rs reading it, then the reverse on a second empty
cache. Equal action keys make the second build of each pair (nearly) all
remote cache hits; the report lists the hits, times and cache traffic.

`bazelignore` regenerates .bazelignore: the build/tool directories plus each
directory below tests/ holding a BUILD file (fixture workspaces, not packages
of this one), cut at tests/fixtures/<case>/<dir>. `--check` only compares.
Python 3.11+ standard library only.
"""

from __future__ import annotations

import argparse
import collections
import dataclasses
import http.server
import importlib.util
import os
from pathlib import Path
import re
import shutil
import subprocess
import sys
import threading
import time


ROOT = Path(__file__).resolve().parents[1]
TARGET = "//:bazel-rs"
BAZELIGNORE_HEADER = """\
# Generated by `python3 scripts/self_build.py bazelignore` (docs/SELF_BUILD.md):
# build outputs, local tool caches, and every test fixture directory that holds
# a BUILD file (the fixtures are separate workspaces, not packages of this one).
# tests/test_self_build.py checks that this list is current.
"""
BAZELIGNORE_FIXED = [".direnv", ".git", "artifacts", "bazel-rs-out", "target"]
# INFO: 1176 processes: 417 internal, 759 remote cache hit.
PROCESSES_RE = re.compile(r"^INFO: (\d+) process(?:es)?: (.*?)\.?$", re.M)
ELAPSED_RE = re.compile(r"^INFO: Elapsed time: ([0-9.]+)s", re.M)


class SelfBuildError(Exception):
    pass


# --------------------------------------------------------------------------
# .bazelignore


def tracked_files(root: Path) -> list[str]:
    out = subprocess.run(
        ["git", "ls-files", "-z"], cwd=root, check=True, capture_output=True
    ).stdout
    return [p for p in out.decode().split("\0") if p]


def bazelignore_entries(files: list[str]) -> list[str]:
    """The fixed entries plus the shallowest fixture directories with BUILD files."""
    dirs = set()
    for path in files:
        parts = path.split("/")
        if parts[-1] in ("BUILD", "BUILD.bazel") and len(parts) > 1 and parts[0] == "tests":
            dirs.add("/".join(parts[: min(len(parts) - 1, 4)]))
    kept: list[str] = []
    for d in sorted(dirs):
        if not any(d == k or d.startswith(k + "/") for k in kept):
            kept.append(d)
    return BAZELIGNORE_FIXED + kept


def bazelignore_text(files: list[str]) -> str:
    return BAZELIGNORE_HEADER + "".join(e + "\n" for e in bazelignore_entries(files))


