def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    sub = parser.add_subparsers(dest="command", required=True)
    p_check = sub.add_parser("check", help="build, smoke-test and test //... with one Bazel")
    p_check.add_argument("--bazel", default=shutil.which("bazel-rs") or "bazel-rs")
    p_check.add_argument(
        "--state-dir",
        type=Path,
        default=Path.home() / ".cache" / "bazel-rs" / "self-build",
        help="bazel-rs --cache-dir, or genuine Bazel's --output_user_root",
    )
    p_check.add_argument("--scratch", type=Path, help="smoke-test directory (default: <state-dir>/smoke)")
    p_check.add_argument("--no-test", action="store_true", help="skip `test //...`")
    p_check.add_argument("args", nargs="*", help="extra build/test options")
    p_cmp = sub.add_parser("compare", help="genuine vs bazel-rs through a shared remote cache")
    p_cmp.add_argument("--genuine", required=True)
    p_cmp.add_argument("--bazel-rs", default=shutil.which("bazel-rs") or "bazel-rs")
    p_cmp.add_argument("--work-dir", type=Path, required=True)
    p_cmp.add_argument("args", nargs="*", help="extra build options")
    p_ign = sub.add_parser("bazelignore", help="regenerate .bazelignore")
    p_ign.add_argument("--check", action="store_true")
    opts = parser.parse_args(argv)
    try:
        if opts.command == "bazelignore":
            want = bazelignore_text(tracked_files(ROOT))
            path = ROOT / ".bazelignore"
            if opts.check:
                if not path.exists() or path.read_text() != want:
                    print(".bazelignore is stale: run scripts/self_build.py bazelignore", file=sys.stderr)
                    return 1
                return 0
            path.write_text(want)
            return 0
        if opts.command == "check":
            bazel = Bazel.detect(opts.bazel, opts.state_dir.resolve())
            scratch = (opts.scratch or opts.state_dir / "smoke").resolve()
            check(bazel, scratch, not opts.no_test, opts.args)
            return 0
        work = opts.work_dir.resolve()
        if work.exists() and any(work.iterdir()):
            raise SelfBuildError(f"--work-dir {work} must be empty or absent (cold builds)")
        rows = compare(opts.genuine, opts.bazel_rs, work, opts.args)
        print(report(rows))
        return 0
    except SelfBuildError as error:
        print(f"self_build: {error}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    sys.exit(main())
