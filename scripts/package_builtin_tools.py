DEFAULT_PLATFORM = "linux-x86_64"
PINNED = PLATFORMS[DEFAULT_PLATFORM]
ARCHIVE = "embedded_tools.tar.gz"
MANIFEST = "manifest.json"
MODULE = "MODULE.bazel"
PREFIX = "embedded_tools/"
INSTALLED_MODE = 0o755


def _sha256(data):
    return hashlib.sha256(data).hexdigest()


def _validate_entry(info):
    """Validate raw ZIP names before normalization could hide traversal/aliases."""
    name = info.orig_filename
    directory = name.endswith("/")
    path = name[:-1] if directory else name
    if (not path or "\\" in name or ":" in name or "\x00" in name
            or any(part in ("", ".", "..") for part in path.split("/"))):
        raise ValueError(f"unsafe ZIP path: {name!r}")
    kind = stat.S_IFMT(info.external_attr >> 16)
    if kind not in (0, stat.S_IFDIR if directory else stat.S_IFREG):
        raise ValueError(f"link or special ZIP entry: {name!r}")
    if not directory and info.external_attr & 0x10:
        raise ValueError(f"directory attribute on ZIP file: {name!r}")
    if directory and info.file_size:
        raise ValueError(f"nonempty ZIP directory: {name!r}")
    return path, directory


def _build_bundle(distribution, *, expected=PINNED):
    """Return all generated bytes, validating everything before publication."""
    if _sha256(distribution) != expected["distribution_sha256"]:
        raise ValueError("distribution SHA-256 mismatch")
    with zipfile.ZipFile(io.BytesIO(distribution)) as source:
        seen = {}
        selected = {}
        for info in source.infolist():
            path, directory = _validate_entry(info)
            if path in seen:
                raise ValueError(f"duplicate ZIP path: {path!r}")
            seen[path] = directory
            if info.filename.startswith(PREFIX) and not directory:
                selected[info.filename[len(PREFIX):]] = info
        for path in seen:
            for parent in Path(path).parents:
                if seen.get(parent.as_posix()) is False:
                    raise ValueError(f"file/directory ZIP collision: {path!r}")
        if "build-label.txt" not in seen or source.read("build-label.txt") != (
                expected["bazel_version"].encode("ascii")):
            raise ValueError("build-label.txt mismatch")
        if len(selected) != expected["file_count"]:
            raise ValueError("embedded file count mismatch")
        if sum(info.file_size for info in selected.values()) != expected["total_size"]:
            raise ValueError("embedded total size mismatch")
        files = {path: source.read(selected[path]) for path in sorted(selected)}
    if MODULE not in files or _sha256(files[MODULE]) != expected["module_sha256"]:
        raise ValueError("MODULE.bazel SHA-256 mismatch")
    if sum(map(len, files.values())) != expected["total_size"]:
        raise ValueError("decoded embedded total size mismatch")

    compressed = io.BytesIO()
    # Explicit empty filename prevents the input/output path entering the header.
    with gzip.GzipFile(filename="", fileobj=compressed, mode="wb",
                       compresslevel=9, mtime=0) as gz:
        # USTAR emits no PAX/GNU extension records. Oversized names fail closed.
        with tarfile.open(fileobj=gz, mode="w", format=tarfile.USTAR_FORMAT) as tar:
            for path, content in files.items():
                info = tarfile.TarInfo(path)
                info.size = len(content)
                info.mode = INSTALLED_MODE
                info.uid = info.gid = info.mtime = 0
                info.uname = info.gname = ""
                tar.addfile(info, io.BytesIO(content))
    archive = compressed.getvalue()
    manifest = {
        "schema_version": 1,
        **{key: expected[key] for key in (
            "bazel_version", "platform", "source_revision", "distribution_url",
            "distribution_sha256",
        )},
        "archive_sha256": _sha256(archive),
        "file_count": len(files),
        "total_size": sum(map(len, files.values())),
        "files": [
            {"path": path, "size": len(content), "sha256": _sha256(content),
             "mode": INSTALLED_MODE}
            for path, content in files.items()
        ],
    }
    return {
        ARCHIVE: archive,
        MANIFEST: (json.dumps(manifest, indent=2, sort_keys=True) + "\n").encode("utf-8"),
        MODULE: files[MODULE],
    }


def _publish(output_dir, bundle):
    """Stage every output first; roll back completed replacements on an error.

    This is a development tool, not a concurrent runtime resource updater. Each
    replacement is atomic, but the group is not atomic against power loss or
    concurrent readers. LICENSE and PROVENANCE.md are never rewritten here.
    """
    output_dir.mkdir(parents=True, exist_ok=True)
    for name in bundle:
        target = output_dir / name
        if target.is_symlink() or (target.exists() and not target.is_file()):
            raise ValueError(f"output is not a regular file: {target}")
    with tempfile.TemporaryDirectory(prefix=".package-", dir=output_dir) as temporary:
        stage = Path(temporary)
        for name, content in bundle.items():
            (stage / name).write_bytes(content)
            (stage / name).chmod(0o644)
            target = output_dir / name
            if target.exists():
                backup = stage / (name + ".old")
                backup.write_bytes(target.read_bytes())
                backup.chmod(stat.S_IMODE(target.stat().st_mode))
        replaced = []
        try:
            for name in bundle:
                os.replace(stage / name, output_dir / name)
                replaced.append(name)
        except OSError:
            for name in reversed(replaced):
                backup = stage / (name + ".old")
                if backup.exists():
                    os.replace(backup, output_dir / name)
                else:
                    (output_dir / name).unlink()
            raise


def _check(output_dir, bundle):
    mismatches = [name for name, content in bundle.items()
                  if (output_dir / name).is_symlink()
                  or not (output_dir / name).is_file()
                  or (output_dir / name).read_bytes() != content]
    if mismatches:
        raise ValueError("bundle differs: " + ", ".join(mismatches))


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--platform", choices=sorted(PLATFORMS), default=DEFAULT_PLATFORM,
                        help="pinned distribution to package (default: %(default)s)")
    parser.add_argument("--distribution", type=Path,
                        help="the official binary (default: "
                             ".direnv/reference/bazel-9.3.0-<platform>)")
    parser.add_argument("--output-dir", type=Path,
                        help="default: resources/bazel_tools/<platform>")
    parser.add_argument("--check", "--verify", action="store_true",
                        help="regenerate in memory and compare, without writing")
    args = parser.parse_args(argv)
    pinned = PLATFORMS[args.platform]
    if args.distribution is None:
        args.distribution = (ROOT / ".direnv/reference"
                             / f"bazel-{pinned['bazel_version']}-{args.platform}")
    if args.output_dir is None:
        args.output_dir = ROOT / "resources/bazel_tools" / args.platform
    try:
        bundle = _build_bundle(args.distribution.read_bytes(), expected=pinned)
        if args.check:
            _check(args.output_dir, bundle)
        else:
            _publish(args.output_dir, bundle)
        summary = json.loads(bundle[MANIFEST])
        del summary["files"]
        summary["check"] = args.check
        print(json.dumps(summary, sort_keys=True))
        return 0
    except (OSError, ValueError, zipfile.BadZipFile, tarfile.TarError) as error:
        print(f"package_builtin_tools: {error}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    sys.exit(main())
