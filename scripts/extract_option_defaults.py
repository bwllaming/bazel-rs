#!/usr/bin/env python3
"""Regenerate src/option_source_defaults.rs from the pinned Bazel sources.

Usage:
  extract_option_defaults.py --source /tmp/opencode/bazel-9.3.1-reference > src/option_source_defaults.rs

Every `@Option(name = ..., defaultValue = "...")` field of
src/main/java (string-literal defaults only; `null` and constant-expression
defaults are left out, so crate::option_defaults never treats them as
known). An option defined twice with different defaults (`output` of the
query commands, `write_command_log`) is left out too: the per-command
`help` defaults (src/help_topics.rs) decide those.
"""

import argparse
import glob
import os
import re
import subprocess

OPTION = re.compile(
    r'@Option\s*\((.*?)\)\s*(?:@\w+(?:\([^)]*\))?\s*)*public\s+[\w<>,.?\[\] ]+\s+\w+\s*;', re.S)
NAME = re.compile(r'\bname\s*=\s*"([^"]+)"')
DEFAULT = re.compile(r'\bdefaultValue\s*=\s*((?:"(?:[^"\\]|\\.)*"\s*\+?\s*)+|[\w.]+)')
LITERAL = re.compile(r'"((?:[^"\\]|\\.)*)"')


def java_unescape(text):
    return re.sub(r'\\(.)', lambda m: {'n': '\n', 't': '\t'}.get(m.group(1), m.group(1)), text)


def rust(text):
    return '"' + text.replace('\\', '\\\\').replace('"', '\\"').replace('\n', '\\n') + '"'


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--source', required=True)
    args = parser.parse_args()
    root = os.path.join(args.source, 'src/main/java')
    defaults = {}
    conflicting = set()
    for path in sorted(glob.glob(os.path.join(root, '**/*.java'), recursive=True)):
        text = open(path, errors='replace').read()
        if '@Option(' not in text:
            continue
        for match in OPTION.finditer(text):
            body = match.group(1)
            name = NAME.search(body)
            default = DEFAULT.search(body)
            if not name or not default:
                continue
            raw = default.group(1)
            value = (java_unescape(''.join(LITERAL.findall(raw)))
                     if raw.startswith('"') else None)
            name = name.group(1)
            if name in defaults and defaults[name] != value:
                conflicting.add(name)
            defaults[name] = value
    head = subprocess.run(['git', '-C', args.source, 'rev-parse', 'HEAD'], capture_output=True,
                          text=True).stdout.strip()
    print('//! Generated by scripts/extract_option_defaults.py from the pinned Bazel 9.3.1')
    print(f'//! source (git HEAD {head}); do not edit.')
    print('//! The string-literal `defaultValue` of every `@Option` (name, default).')
    print('#[rustfmt::skip]')
    print('pub(crate) const SOURCE_DEFAULTS: &[(&str, &str)] = &[')
    for name in sorted(defaults):
        value = defaults[name]
        if value is None or value == 'null' or name in conflicting:
            continue
        print(f'    ({rust(name)}, {rust(value)}),')
    print('];')


if __name__ == '__main__':
    main()
