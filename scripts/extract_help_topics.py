#!/usr/bin/env python3
"""Regenerate src/help_topics.rs from tests/fixtures/help/reference_receipt.json.

The receipt (tests/fixtures/help/capture.py) holds genuine Bazel 9.3.1's
`help` output. Kept: each command's help template (the text before its
option listing; the `[bazel release 9.3.1]` header line dropped), the
`startup_options` template, the `target-syntax` and `info-keys` pages, the
index, and each documented option's type description as OptionsUsage prints
it after the option's name (converter type descriptions are not part of
`help flags-as-proto`; the `--output` options of different commands differ). Option membership,
categories, defaults and order come from src/option_metadata.rs.

Usage: extract_help_topics.py > src/help_topics.rs
"""

import json
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
RECEIPT = os.path.join(HERE, "..", "tests", "fixtures", "help", "reference_receipt.json")
COMMANDS = ['aquery', 'build', 'canonicalize-flags', 'clean', 'config', 'coverage', 'cquery',
            'dump', 'fetch', 'help', 'info', 'license', 'mobile-install', 'mod', 'print_action',
            'query', 'run', 'shutdown', 'test', 'vendor', 'version', 'startup']
# OptionFilterDescriptions.getOptionCategoriesEnumDescription, inverted.
CATEGORIES = {
    'Options that appear before the command and are parsed by the client': 'BAZEL_CLIENT_OPTIONS',
    'Options that control build execution': 'EXECUTION_STRATEGY',
    'Options that configure the toolchain used for action execution': 'TOOLCHAIN',
    'Options that control the output of the command': 'OUTPUT_SELECTION',
    'Options that let the user configure the intended output, affecting its value, as opposed '
    'to its existence': 'OUTPUT_PARAMETERS',
    'Options that affect how strictly Bazel enforces valid build inputs (rule definitions,  '
    'flag combinations, etc.)': 'INPUT_STRICTNESS',
    'Options that affect the signing outputs of a build': 'SIGNING',
    'This option affects semantics of the Starlark language or the build API accessible to '
    'BUILD files, .bzl files, or WORKSPACE files.': 'STARLARK_SEMANTICS',
    'Options that govern the behavior of the test environment or test runner': 'TESTING',
    'Options relating to query output and semantics': 'QUERY',
    'Options relating to the output and semantics of the `mod` subcommand': 'MOD_COMMAND',
    'Options relating to Bzlmod output and semantics': 'BZLMOD',
    'Options that trigger optimizations of the build time': 'BUILD_TIME_OPTIMIZATION',
    'Options that affect the verbosity, format or location of logging': 'LOGGING',
    'Options specifying or altering a generic input to a Bazel command that does not fall '
    'into other categories.': 'GENERIC_INPUTS',
    'Remote caching and execution options': 'REMOTE',
    'Miscellaneous options, not otherwise categorized.': 'UNCATEGORIZED',
}
LINE = re.compile(r'^  --(\[no\])?([\w:/.-]+)( \[-\w\])?( \((.*?)(; (may be used multiple times|default: .*))?\))?$')


def rust(text):
    return '"' + text.replace('\\', '\\\\').replace('"', '\\"').replace('\n', '\\n') + '"'


def body(text):
    lines = text.split('\n')
    if lines and lines[0].strip().startswith('[bazel release'):
        lines = lines[1:]
    return '\n'.join(lines).rstrip()


def main():
    receipt = json.load(open(RECEIPT))
    table = receipt['lines']
    templates, pages = [], []
    listed = {}
    for case in receipt['cases']:
        args = case['args']
        if 'template' in case:
            templates.append((args[0], body(case['template'])))
            command = 'startup' if args[0] == 'startup_options' else args[0]
            category = None
            for index in case['options']:
                line = table[index]
                if not line.startswith('  --'):
                    category = CATEGORIES.get(line.rstrip(':'))
                    continue
                if not LINE.match(line) or category is None:
                    continue
                key = (line[4:], category)
                listed[key] = listed.get(key, 0) | (1 << COMMANDS.index(command))
        elif case.get('stdout'):
            pages.append((args[0] if args else '', body(case['stdout'])))
    def name(text):
        return text.split(' ')[0].replace('[no]', '')
    rows = ['    ({}, {}, {:#x}),'.format(rust(line), rust(category), mask)
            for (line, category), mask in sorted(listed.items(), key=lambda item: (name(item[0][0]), item[0]))]
    out = [
        '//! Generated by scripts/extract_help_topics.py from tests/fixtures/help/reference_receipt.json',
        '//! (genuine Bazel 9.3.1 `help`, sha256 {}); do not edit.'.format(receipt['bazel_sha256']),
        '',
        '/// Help templates of the commands and `startup_options` (before the options).',
        '#[rustfmt::skip]',
        'pub(crate) const TEMPLATES: &[(&str, &str)] = &[',
        *['    ({}, {}),'.format(rust(topic), rust(text)) for topic, text in templates],
        '];',
        '',
        '/// The index (`""`), `target-syntax` and `info-keys`.',
        '#[rustfmt::skip]',
        'pub(crate) const PAGES: &[(&str, &str)] = &[',
        *['    ({}, {}),'.format(rust(topic), rust(text)) for topic, text in pages],
        '];',
        '',
        '/// (usage line after `  --`, documentation category, commands as a bit set over',
        '/// crate::option_metadata::COMMANDS): every option a genuine help page lists.',
        '#[rustfmt::skip]',
        'pub(crate) const OPTION_LINES: &[(&str, &str, u32)] = &[',
        *rows,
        '];',
    ]
    sys.stdout.write('\n'.join(out) + '\n')


if __name__ == '__main__':
    main()
