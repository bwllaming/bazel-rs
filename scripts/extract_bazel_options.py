#!/usr/bin/env python3
"""Regenerate src/bazel_options.rs from a pinned Bazel 9.3 source tree.

Usage: extract_bazel_options.py /path/to/bazel-9.3-reference > src/bazel_options.rs

Lists every @Option of every FragmentOptions subclass (BuildOptionDetails
covers only fragment options, analysis/config/BuildOptionDetails.java:56-84),
excluding INTERNAL options, which BuildOptionDetails ignores. Static text
extraction only; nothing is executed.
"""

import os
import re
import subprocess
import sys


PINNED_COMMIT = 'e89755babf3e941bc1e9d8120b1cd48854ab9dfa'


def main(reference):
    head = subprocess.run(['git', '-C', reference, 'rev-parse', 'HEAD'], check=True,
                          capture_output=True, text=True).stdout.strip()
    if head != PINNED_COMMIT:
        raise SystemExit(f'{reference} is at {head}, not the pinned Bazel 9.3.0 commit {PINNED_COMMIT}')
    root = os.path.join(reference, 'src/main/java')
    declared = []
    texts = {}
    for directory, _, files in os.walk(root):
        for name in files:
            if name.endswith('.java'):
                path = os.path.join(directory, name)
                text = open(path, encoding='utf-8').read()
                texts[path] = text
                for match in re.finditer(r'class\s+(\w+)(?:<[^>{]*>)?\s+extends\s+([\w.]+)', text):
                    declared.append((match.group(1), match.group(2).split('.')[-1], path))
    parents = {}
    for name, parent, _ in declared:
        parents.setdefault(name, set()).add(parent)

    def fragment(name, seen=()):
        return name == 'FragmentOptions' or (
            name not in seen and any(fragment(p, seen + (name,)) for p in parents.get(name, ())))

    options = []
    for name, parent, path in sorted(declared, key=lambda d: (d[2], d[0])):
        if not fragment(parent):
            continue
        text = texts[path]
        start = re.search(r'class\s+' + name + r'\b[^{]*\{', text).end()
        depth, end = 1, start
        while depth:
            depth += {'{': 1, '}': -1}.get(text[end], 0)
            end += 1
        body = text[start:end]
        for annotation in re.finditer(r'@Option\s*\(', body):
            index, depth = annotation.end(), 1
            while depth:
                char = body[index]
                if char == '"':
                    index += 1
                    while body[index] != '"':
                        index += 2 if body[index] == '\\' else 1
                depth += {'(': 1, ')': -1}.get(char, 0)
                index += 1
            arguments = body[annotation.end():index - 1]
            option = re.search(r'\bname\s*=\s*"([^"]*)"', arguments)
            if not option:
                continue
            old = re.search(r'\boldName\s*=\s*"([^"]*)"', arguments)
            tags = re.search(r'metadataTags\s*=\s*\{([^}]*)\}', arguments)
            tags = tags.group(1) if tags else ''
            if 'INTERNAL' in tags:
                continue
            line = text[:start].count('\n') + body[:annotation.start()].count('\n') + 1
            options.append((option.group(1), old.group(1) if old else '',
                            'NON_CONFIGURABLE' in tags,
                            os.path.relpath(path, root + '/com/google/devtools/build/lib'), line))
    print('//! Generated by scripts/extract_bazel_options.py from the pinned Bazel 9.3')
    print(f'//! source (`/tmp/opencode/bazel-9.3-reference`, git HEAD {head}); do not edit.')
    print('//! Every non-INTERNAL `@Option` of every `FragmentOptions` subclass:')
    print('//! (name, old name or "", NON_CONFIGURABLE, defining file:line).')
    print('#[rustfmt::skip]')
    print('pub(crate) const FRAGMENT_OPTIONS: &[(&str, &str, bool, &str)] = &[')
    for name, old, nonconfigurable, path, line in sorted(options):
        print(f'    ("{name}", "{old}", {"true" if nonconfigurable else "false"}, "{path}:{line}"),')
    print('];')


if __name__ == '__main__':
    main(sys.argv[1])
