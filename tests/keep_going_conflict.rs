//! `--keep_going` and an action conflict on a target's second output
//! (docs/KEEP_GOING.md): the conflicting target fails whole — none of its
//! outputs is registered, not even those before the conflicting one — so a
//! later target sharing such an output (the same action) produces it
//! itself. Before, the failed commit's first output stayed registered under
//! the failed target's action and the sharer's planning failed with
//! `missing producing action`.
//!
//! Genuine receipt (Bazel 9.3.1, `bazel --batch --ignore_all_rc_files
//! build --nobuild -k //k:e1 //k:fa //k:fc //k:fd //k:ok` on [`MODULE`],
//! [`KG`], [`BUILD`], captured 2026-11-13, exit 1, stderr sha256
//! ba5c6c709db0f4f0…): `file 'k/q.txt' is generated by these conflicting
//! actions: Label: //k:fa, //k:e1`, `errors encountered while analyzing
//! target '//k:fa'`, `Analysis succeeded for only 3 of 5 top-level targets`
//! (e1, fc and ok built). **Divergence** (the conflict model): Bazel finds
//! conflicts after analysis, so `//k:fd` (above `//k:fa`) is analyzed (its
//! print shows) and not built without a warning of its own; natively the
//! conflict fails `//k:fa` at its commit and `//k:fd` is skipped (warned,
//! `Analysis failed`).
#![allow(clippy::disallowed_methods)] // test harness: starts processes directly (clippy.toml)
include!("support/verify_env.rs");
include!("support/explicit_modules.rs");

use std::fs;
use std::path::Path;
use std::process::Command;

const MODULE: &str = "module(name = \"m\")\n";

const KG: &str = r#"def _pair_impl(ctx):
    print("pair %s" % ctx.label)
    outs = []
    for path, content in ctx.attr.writes.items():
        out = ctx.actions.declare_file(path)
        ctx.actions.write(out, content)
        outs.append(out)
    files = depset(outs, transitive = [dep[DefaultInfo].files for dep in ctx.attr.deps])
    return [DefaultInfo(files = files)]

pair = rule(implementation = _pair_impl, attrs = {"writes": attr.string_dict(), "deps": attr.label_list()})
"#;

const BUILD: &str = r#"load("//rules:kg.bzl", "pair")
pair(name = "e1", writes = {"q.txt": "E"})
pair(name = "fa", writes = {"p.txt": "same", "q.txt": "A"})
pair(name = "fc", writes = {"p.txt": "same"})
pair(name = "fd", writes = {"d.txt": "D"}, deps = [":fa"])
pair(name = "ok", writes = {"o.txt": "O"})
"#;

const TARGETS: &[&str] = &["//k:e1", "//k:fa", "//k:fc", "//k:fd", "//k:ok"];

fn run(
    root: &Path,
    mode: &str,
    threads: u32,
    env: &[(&str, &str)],
    args: &[&str],
) -> (Option<i32>, String, String) {
    let _ = fs::remove_dir_all(root.join("cache"));
    let output = Command::new(env!("CARGO_BIN_EXE_bazel-rs"))
        .current_dir(root)
        .env_clear()
        .envs(verifier_environment())
        .env("PATH", "/usr/bin:/bin")
        .env("HOME", root.join("home"))
        .env("TMPDIR", root.join("tmp"))
        .env("BAZEL_RS_CACHE_GC", "off")
        .env("BAZEL_RS_SNAPSHOT", "off")
        .env("BAZEL_RS_ANALYSIS", mode)
        .envs(env.iter().copied())
        .args(["--ignore_all_rc_files", "--cache-dir=cache", "build"])
        .args([
            "--lockfile_mode=off",
            "--memory-limit=2048",
            &format!("--loading_phase_threads={threads}"),
            "-k",
        ])
        .args(args)
        .args(TARGETS)
        .explicit_modules()
        .output()
        .unwrap();
    (
        output.status.code(),
        String::from_utf8_lossy(&output.stderr).into_owned(),
        String::from_utf8_lossy(&output.stdout).into_owned(),
    )
}

fn stable(stderr: &str) -> String {
    stderr
        .lines()
        .filter(|line| {
            !line.starts_with("INFO: Elapsed time")
                && !line.starts_with("bazel-rs: memory limit")
                && !line.starts_with("bazel-rs: peak RSS")
                && !line.starts_with("PERF")
        })
        .collect::<Vec<_>>()
        .join("\n")
}

#[test]
fn keep_going_a_conflict_on_a_second_output_registers_none_of_the_targets_outputs() {
    let temp = tempfile::tempdir_in(test_temp::root()).unwrap();
    let root = temp.path();
    for (path, text) in [
        ("MODULE.bazel", MODULE),
        ("rules/BUILD.bazel", ""),
        ("rules/kg.bzl", KG),
        ("k/BUILD.bazel", BUILD),
    ] {
        let path = root.join(path);
        fs::create_dir_all(path.parent().unwrap()).unwrap();
        fs::write(path, text).unwrap();
    }
    for directory in ["home", "tmp"] {
        fs::create_dir(root.join(directory)).unwrap();
    }
    const FROZEN: (&str, &str) = ("BAZEL_RS_EVAL_FROZEN_PREPARES", "all");
    for args in [&["--nobuild"][..], &[]] {
        let (_, walk, _) = run(root, "walk", 8, &[], args);
        for (mode, threads, env) in [
            ("walk", 8, &[][..]),
            ("eval", 8, &[]),
            ("eval", 1, &[]),
            ("eval", 8, &[FROZEN]),
            ("eval", 2, &[FROZEN, ("BAZEL_RS_EVAL_JITTER", "300")]),
        ] {
            let (code, stderr, _) = run(root, mode, threads, env, args);
            let what = format!("{mode}, {threads} threads, {env:?}, {args:?}: {stderr}");
            assert_eq!(code, Some(1), "{what}");
            assert!(!stderr.contains("missing producing action"), "{what}");
            assert!(
                stderr.contains("file 'k/q.txt' is generated by these conflicting actions:\nLabel: //k:fa, //k:e1"),
                "{what}"
            );
            assert!(
                stderr.contains("errors encountered while analyzing target '//k:fa'"),
                "{what}"
            );
            let summary = if args.is_empty() { "Build" } else { "Analysis" };
            assert!(
                stderr.contains(&format!(
                    "INFO: {summary} succeeded for only 3 of 5 top-level targets"
                )),
                "{what}"
            );
            assert_eq!(stable(&stderr), stable(&walk), "{what}");
        }
    }
}
