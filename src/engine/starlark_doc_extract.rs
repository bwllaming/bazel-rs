//! The native `starlark_doc_extract` rule
//! (rules/starlarkdocextract/StarlarkDocExtract.java,
//! docs/STARLARK_DOC_EXTRACT.md): the `src` module loaded at analysis, its
//! loads checked against the `deps` files, and its ModuleInfo
//! (crate::starlark_doc_extract) written as `NAME.binaryproto` (files to
//! build) and `NAME.textproto` (an implicit output built on request).
use super::*;

/// What a starlark_doc_extract target writes.
pub(super) struct DocExtractOutput {
    pub binary: Vec<u8>,
    pub text: Vec<u8>,
}

impl Engine {
    /// StarlarkDocExtract.create up to the two file writes.
    pub(super) fn starlark_doc_extract_output(
        &mut self,
        rule: &Rule,
        config: ConfigId,
        built: &BTreeMap<ConfiguredTargetKey, Artifacts>,
        declared: &Declared,
    ) -> Result<DocExtractOutput, String> {
        use crate::custom_rule::AttrValue;
        let shown = crate::rule_declarations::canonical_form(&rule.label);
        let location = rule.location.clone();
        // RuleContext.attributeError / ruleError prefixes.
        let attribute_error = |attribute: &str, message: String| {
            located(
                location.as_deref(),
                format!("in {attribute} attribute of starlark_doc_extract rule {shown}: {message}"),
            )
        };
        let rule_error = |message: String| {
            located(
                location.as_deref(),
                format!("in starlark_doc_extract rule {shown}: {message}"),
            )
        };
        let attrs = rule
            .native
            .as_ref()
            .map(|native| native.attrs.clone())
            .ok_or_else(|| rule_error("missing attributes".into()))?;
        let mapping = self.repositories.mapping("").cloned().unwrap_or_default();
        let display = crate::starlark_doc_extract::LabelRenderer {
            mapping: mapping.clone(),
            main_repo_name: None,
        };
        // getSourceFileLabel: the single source artifact of `src`.
        let Some(AttrValue::Label(Some(src))) = attrs.get("src") else {
            return Err(attribute_error("src", "missing value".into()));
        };
        let src = self.resolve_rule_src(rule, src)?;
        let generated = |this: &mut Self, label: &Label| -> Result<Option<String>, String> {
            Ok(match this.target(label)? {
                Target::Output(generating, name) => Some(format!(
                    "{} (generated by rule {})",
                    if generating.label.package.is_empty() {
                        name.clone()
                    } else {
                        format!("{}/{name}", generating.label.package)
                    },
                    display.render_label(&generating.label, false)
                )),
                _ => None,
            })
        };
        if let Some(described) = generated(self, &src)? {
            return Err(attribute_error(
                "src",
                format!("{described} is not a source file and cannot be loaded in Starlark"),
            ));
        }
        let artifacts = self.artifacts(&src, config, built, declared)?;
        let [artifact] = artifacts.as_slice() else {
            return Err(attribute_error(
                "src",
                format!(
                    "'{}' must produce a single file",
                    display.render_label(&src, false)
                ),
            ));
        };
        let file = artifact.file();
        if !file.is_source {
            return Err(attribute_error(
                "src",
                format!(
                    "{} is not a source file and cannot be loaded in Starlark",
                    file.short_path
                ),
            ));
        }
        let module_label = Label::parse_canonical(&file.owner).unwrap_or(src);
        // loadModule: BzlLoadValue.keyForBuild(label).
        let prints = crate::loading::LoadPrints::default();
        let loaded = crate::loading::load_doc_module_in(
            self.repositories.clone(),
            &module_label,
            &self.repositories.build_phase_globals().1,
            &prints,
        );
        self.emit_load_prints(prints.take());
        let loaded = loaded.map_err(|error| attribute_error("src", error))?;
        // verifyModuleDeps: the module's transitive loads must be source
        // files to build of `deps`.
        let mut known = BTreeSet::new();
        let mut derived = Vec::new();
        if let Some(AttrValue::Labels(deps)) = attrs.get("deps") {
            for text in deps {
                let label = self.resolve_rule_src(rule, text)?;
                for artifact in self.artifacts(&label, config, built, declared)? {
                    let file = artifact.file();
                    if file.is_source {
                        if let Ok(owner) = Label::parse_canonical(&file.owner) {
                            known.insert(owner);
                        }
                    } else {
                        let owner = Label::parse_canonical(&file.owner)
                            .map(|owner| display.render_label(&owner, false))
                            .unwrap_or_else(|_| file.owner.clone());
                        let described = format!("{} (generated by rule {owner})", file.short_path);
                        if !derived.contains(&described) {
                            derived.push(described);
                        }
                    }
                }
            }
        }
        // BazelModuleContext.visitLoadGraphRecursively: preorder over the
        // direct loads; an unknown module is reported, not entered.
        let mut unknown = Vec::new();
        let mut visited = BTreeSet::new();
        let mut stack: Vec<Label> = loaded
            .load_graph
            .get(&module_label)
            .cloned()
            .unwrap_or_default()
            .into_iter()
            .rev()
            .collect();
        while let Some(label) = stack.pop() {
            if !visited.insert(label.clone()) {
                continue;
            }
            if !known.contains(&label) {
                unknown.push(display.render_label(&label, false));
                continue;
            }
            if let Some(loads) = loaded.load_graph.get(&label) {
                stack.extend(loads.iter().rev().cloned());
            }
        }
        if !unknown.is_empty() {
            let mut message = format!(
                "missing bzl_library targets for Starlark module(s) {}",
                unknown.join(", ")
            );
            if !derived.is_empty() {
                message.push_str(&format!(
                    "\nNote the following are generated file(s) and cannot be loaded in Starlark: {}",
                    derived.join(", ")
                ));
            }
            return Err(attribute_error("deps", message));
        }
        // render_main_repo_name: the root module's name, else the
        // workspace name.
        let main_repo_name = if matches!(
            attrs.get("render_main_repo_name"),
            Some(AttrValue::Bool(true))
        ) {
            let name = self
                .repositories
                .associated_module("")
                .map(|(name, _)| name)
                .unwrap_or_default();
            Some(if name.is_empty() {
                "_main".to_owned()
            } else {
                name
            })
        } else {
            None
        };
        let symbol_names = match attrs.get("symbol_names") {
            Some(AttrValue::Strings(names)) => names.clone(),
            _ => Vec::new(),
        };
        let source = crate::starlark_doc_extract::SourceInfo::scan(
            &module_label.to_string(),
            &loaded.source,
        )
        .map_err(|error| attribute_error("src", error))?;
        let filename = loaded.path.display().to_string();
        let options = crate::starlark_doc_extract::ExtractOptions {
            label: &module_label,
            filename: &filename,
            renderer: crate::starlark_doc_extract::LabelRenderer {
                mapping,
                main_repo_name,
            },
            symbol_names: &symbol_names,
            allow_unused_doc_comments: matches!(
                attrs.get("allow_unused_doc_comments"),
                Some(AttrValue::Bool(true))
            ),
        };
        let info = crate::starlark_doc_extract::extract(&loaded.module, &source, &options)
            .map_err(rule_error)?;
        Ok(DocExtractOutput {
            binary: info.to_bytes(),
            text: info.to_text().into_bytes(),
        })
    }
}
