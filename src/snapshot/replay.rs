/// Marker paths bracketing the record mode's replay dry run (after the
/// recording window closed) and, on the replaying thread, each replayed
/// execution (`<MARKER_REPLAY_EXEC><escaped canonical name>` until
/// [`MARKER_REPLAY_EXEC_END`]): scripts/snapshot_fs_audit.py checks that a
/// replay touches only recorded paths, the store (stages, pinned trees)
/// and — inside the executions of impure rules — host paths. They never
/// exist.
pub const MARKER_REPLAY_BEGIN: &str = "/.bazel-rs-snapshot-marker/replay-begin";
pub const MARKER_REPLAY_END: &str = "/.bazel-rs-snapshot-marker/replay-end";
pub const MARKER_REPLAY_EXEC: &str = "/.bazel-rs-snapshot-marker/replay-exec/";
pub const MARKER_REPLAY_EXEC_END: &str = "/.bazel-rs-snapshot-marker/replay-exec-end";

fn marker(path: &str) {
    let _ = std::fs::symlink_metadata(path);
}

fn lock<T>(mutex: &Mutex<T>) -> MutexGuard<'_, T> {
    mutex.lock().unwrap_or_else(PoisonError::into_inner)
}

// ---- records ---------------------------------------------------------------

/// How a replay loads a local rule's definition: exactly as the recorded run
/// did.
#[derive(Clone, Debug, PartialEq, Eq, PartialOrd, Ord)]
pub enum DefinitionSource {
    /// A `use_repo_rule` group: `loading::load_definition_in` of the
    /// definition request's canonical `.bzl` label and public symbol.
    Direct { label: Label, symbol: String },
    /// A module extension's repository: `loading::load_module_extension_in`
    /// of the lockfile `repoRuleId` (`label%symbol`, any visibility), as
    /// `RepositorySet::repositories_from_lock_entry` loads it.
    Ordinary { rule_id: String },
}

impl std::fmt::Display for DefinitionSource {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            Self::Direct { label, symbol } => write!(f, "{label}%{symbol}"),
            Self::Ordinary { rule_id } => f.write_str(rule_id),
        }
    }
}

/// One local repository rule execution of the window: what a replay needs
/// and what it must reproduce.
#[derive(Clone, Debug)]
pub struct ReplayRecord {
    pub canonical: String,
    /// `repository_ctx.original_name` (the declaration's name).
    pub original_name: String,
    pub definition: DefinitionSource,
    /// The rule's `identity` (`<bzl>%<name>`), checked after the load.
    pub identity: String,
    /// The label `repository_ctx` resolves relative paths and Labels in.
    pub definition_label: Label,
    /// The bound attributes (`bind_attributes_where` /
    /// `bind_recorded_attributes_where` output) the execution received.
    pub attributes: BTreeMap<String, AttrValue>,
    /// The published root (`direct/trees/<identity>`).
    pub root: PathBuf,
    pub execution: crate::repository_store::LocalExecution,
    /// What the execution printed (v1: non-empty taints the run).
    pub output: Vec<u8>,
    /// `repository_ctx.os.environ` was read.
    pub environ_read: bool,
    /// Host facilities the execution used (`execute`, `which`, downloads).
    pub facilities: Vec<&'static str>,
    /// The recorded execution's wall time.
    pub elapsed: Duration,
}

impl ReplayRecord {
    /// Impurity flags (the optional purity classes of PLAN-L2 update 1
    /// §(a); diagnostics and the syscall audit only — every record is
    /// replayed): `environ` plus the host facilities, or `-`.
    pub fn flags(&self) -> String {
        let mut flags: Vec<&str> = Vec::new();
        if self.environ_read {
            flags.push("environ");
        }
        flags.extend(self.facilities.iter().copied());
        if flags.is_empty() {
            "-".to_owned()
        } else {
            flags.join(",")
        }
    }
}

/// A pinned repository root, and whether the repository is generated by a
/// repository rule (its links may read host paths, `LinkPolicy`).
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct PinnedRoot {
    pub path: PathBuf,
    pub generated: bool,
}

/// A pinned repository mapping (`RepositorySet::mapping`), plus the
/// apparent names whose first matching extension import in the owning
/// module is an isolated usage (`mapping_for_label` rejects those; usually
/// empty).
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct PinnedMapping {
    pub mapping: BTreeMap<String, String>,
    pub isolated: BTreeSet<String>,
}

/// What a pinned repository set answers from.
#[derive(Clone, Debug, Default, PartialEq, Eq)]
pub struct PinnedTables {
    pub main_root: PathBuf,
    /// The absolute repository store (`source_cache_path`).
    pub source_cache: PathBuf,
    pub roots: BTreeMap<String, PinnedRoot>,
    pub mappings: BTreeMap<String, PinnedMapping>,
}

/// The recorded repository set's configuration a replay reuses. (On a hit,
/// L2-W5 rebuilds it from the command line before the snapshot check:
/// options are part of the snapshot key, the environment is the current
/// one.)
pub struct CaptureContext {
    pub options: crate::module_graph::ResolverOptions,
    /// A fresh snapshot over the recorded set's environment reader.
    pub(crate) environment: crate::repository_environment::Snapshot,
    pub downloads_enabled: bool,
    pub main_root: PathBuf,
    pub source_cache: PathBuf,
}

/// The replay capture of one recording window (or of a test): the records
/// and the pinned tables their replay needs.
#[derive(Default)]
pub struct ReplayCapture {
    records: Mutex<Vec<ReplayRecord>>,
    roots: Mutex<BTreeMap<String, PinnedRoot>>,
    mappings: Mutex<BTreeMap<String, PinnedMapping>>,
    context: OnceLock<CaptureContext>,
}

impl std::fmt::Debug for ReplayCapture {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.write_str("ReplayCapture")
    }
}

impl ReplayCapture {
    /// The configuration of the set whose local rules this capture records
    /// (the first one wins: one repository set per command).
    pub fn set_context(&self, context: impl FnOnce() -> CaptureContext) {
        if self.context.get().is_none() {
            let _ = self.context.set(context());
        }
    }

    pub fn context(&self) -> Option<&CaptureContext> {
        self.context.get()
    }

    /// A `root()` result inside a replay [`scope`] (first one kept).
    pub fn note_root(&self, name: &str, path: &Path, generated: impl FnOnce() -> bool) {
        let mut roots = lock(&self.roots);
        if !roots.contains_key(name) {
            roots.insert(
                name.to_owned(),
                PinnedRoot {
                    path: path.to_path_buf(),
                    generated: generated(),
                },
            );
        }
    }

    /// A `mapping()` result inside a replay [`scope`] (first one kept).
    pub fn note_mapping(
        &self,
        name: &str,
        mapping: &BTreeMap<String, String>,
        isolated: impl FnOnce() -> BTreeSet<String>,
    ) {
        let mut mappings = lock(&self.mappings);
        if !mappings.contains_key(name) {
            mappings.insert(
                name.to_owned(),
                PinnedMapping {
                    mapping: mapping.clone(),
                    isolated: isolated(),
                },
            );
        }
    }

    pub fn record(&self, record: ReplayRecord) {
        lock(&self.records).push(record);
    }

    pub fn records(&self) -> Vec<ReplayRecord> {
        lock(&self.records).clone()
    }

    /// The pinned tables recorded so far.
    pub fn tables(&self) -> Option<PinnedTables> {
        let context = self.context.get()?;
        Some(PinnedTables {
            main_root: context.main_root.clone(),
            source_cache: context.source_cache.clone(),
            roots: lock(&self.roots).clone(),
            mappings: lock(&self.mappings).clone(),
        })
    }
}

static GLOBAL: OnceLock<Arc<ReplayCapture>> = OnceLock::new();

/// Install the process's capture (record mode, when the window opens):
/// repository sets created afterwards record into it.
pub fn install() -> Arc<ReplayCapture> {
    GLOBAL.get_or_init(Arc::default).clone()
}

/// The process's capture, when record mode installed one.
pub fn global() -> Option<Arc<ReplayCapture>> {
    GLOBAL.get().cloned()
}

thread_local! {
    static SCOPE: Cell<u32> = const { Cell::new(0) };
}

/// While the guard lives, `root()` and `mapping()` results on this thread
/// are pinned for replay: around the definition loads of repository rules
/// and around local executions (crate::repository).
pub fn scope() -> Scope {
    SCOPE.with(|depth| depth.set(depth.get() + 1));
    Scope(())
}

/// The guard of [`scope`].
pub struct Scope(());

impl Drop for Scope {
    fn drop(&mut self) {
        SCOPE.with(|depth| depth.set(depth.get().saturating_sub(1)));
    }
}

/// Whether a replay [`scope`] is open on this thread.
pub fn in_scope() -> bool {
    SCOPE.with(|depth| depth.get() > 0)
}

/// A `root()` or `mapping()` lookup of a repository set that records for
/// replay ([`lookups`]).
#[derive(Clone, Debug, PartialEq, Eq)]
pub enum Lookup {
    Root(String),
    Mapping(String),
}

thread_local! {
    /// The open [`lookups`] logs of this thread, innermost last.
    static LOOKUPS: std::cell::RefCell<Vec<Vec<Lookup>>> =
        const { std::cell::RefCell::new(Vec::new()) };
}

/// Run `f` noting the `root()` and `mapping()` lookups it makes of a
/// repository set that records for replay (W6R: the definition `.bzl`
/// cache keeps them with a module, and a hit inside a replay [`scope`]
/// repeats them, so the pinned tables are the uncached loader's whatever
/// scope the module was first evaluated in).
pub fn lookups<R>(f: impl FnOnce() -> R) -> (R, Vec<Lookup>) {
    /// Closes the log, also when `f` unwinds.
    struct Log(usize);
    impl Drop for Log {
        fn drop(&mut self) {
            let _ = LOOKUPS.try_with(|logs| {
                if let Ok(mut logs) = logs.try_borrow_mut() {
                    logs.truncate(self.0);
                }
            });
        }
    }
    let depth = LOOKUPS.with(|logs| {
        let mut logs = logs.borrow_mut();
        logs.push(Vec::new());
        logs.len() - 1
    });
    let guard = Log(depth);
    let result = f();
    let log = LOOKUPS.with(|logs| logs.borrow_mut().get_mut(depth).map(std::mem::take));
    drop(guard);
    (result, log.unwrap_or_default())
}

/// Note `lookup` in this thread's innermost [`lookups`] log, if any.
pub(crate) fn note_lookup(lookup: impl FnOnce() -> Lookup) {
    LOOKUPS.with(|logs| {
        if let Ok(mut logs) = logs.try_borrow_mut()
            && let Some(log) = logs.last_mut()
        {
            let lookup = lookup();
            if !log.contains(&lookup) {
                log.push(lookup);
            }
        }
    });
}

// ---- replay ----------------------------------------------------------------

/// One replayed record.
#[derive(Clone, Debug)]
pub struct Replayed {
    pub canonical: String,
    pub definition: String,
    pub flags: String,
    /// `None`: both digests reproduced; else why not.
    pub mismatch: Option<String>,
    /// The replayed output differs from the recorded one (diagnostic: v1
    /// taints any non-empty output anyway).
    pub output_differs: bool,
    pub output_bytes: usize,
    pub recorded: Duration,
    /// The replayed execution (stage, execute, digests).
    pub wall: Duration,
}

/// One definition loaded for replay (shared by its records, replayed on
/// one thread).
#[derive(Clone, Debug)]
pub struct Definition {
    pub source: String,
    pub records: usize,
    /// The definition load.
    pub wall: Duration,
    /// The thread's CPU time: the load and every replay of its records
    /// (/proc/thread-self/schedstat; current within a scheduler tick).
    pub cpu: Option<Duration>,
    pub error: Option<String>,
}

/// A replay of every record.
#[derive(Clone, Debug, Default)]
pub struct Report {
    pub replayed: Vec<Replayed>,
    pub definitions: Vec<Definition>,
    pub wall: Duration,
    /// Thread CPU time of the replay threads (definition loads and
    /// executions), when /proc provides it (each current within a
    /// scheduler tick).
    pub cpu: Option<Duration>,
    /// CPU time of processes the executions started (`execute`), USER_HZ
    /// resolution.
    pub children_cpu: Option<Duration>,
    pub pinned_roots: usize,
    pub pinned_mappings: usize,
}

impl Report {
    pub fn matched(&self) -> usize {
        self.replayed
            .iter()
            .filter(|replayed| replayed.mismatch.is_none())
            .count()
    }
}

/// This thread's CPU time (/proc/thread-self/schedstat: nanoseconds on the
/// CPU).
fn thread_cpu() -> Option<Duration> {
    let text = std::fs::read_to_string("/proc/thread-self/schedstat").ok()?;
    let nanos = text.split_whitespace().next()?.parse::<u64>().ok()?;
    Some(Duration::from_nanos(nanos))
}

/// CPU time of this process's waited-for children (/proc/self/stat cutime
/// and cstime, in USER_HZ = 100 ticks per second on Linux).
fn children_cpu() -> Option<Duration> {
    let text = std::fs::read_to_string("/proc/self/stat").ok()?;
    // Fields after the parenthesized command name: state is field 3.
    let rest = &text[text.rfind(')')? + 2..];
    let fields: Vec<&str> = rest.split_whitespace().collect();
    // cutime and cstime are fields 16 and 17 (1-based): 13 and 14 here.
    let ticks = fields.get(13)?.parse::<u64>().ok()? + fields.get(14)?.parse::<u64>().ok()?;
    Some(Duration::from_millis(ticks * 10))
}

/// Load one definition the way the recorded run did.
fn load_definition(
    repositories: &Arc<RepositorySet>,
    source: &DefinitionSource,
) -> Result<
    (
        crate::repository_rule::RuleDefinition,
        Vec<starlark::values::OwnedFrozenValue>,
    ),
    String,
> {
    let globals = crate::package::module_bzl_globals();
    let loaded = match source {
        DefinitionSource::Direct { label, symbol } => {
            crate::loading::load_definition_in(repositories.clone(), label, symbol, &globals)?
        }
        DefinitionSource::Ordinary { rule_id } => {
            let (label, rule) = crate::lockfile_extensions::parse_repo_rule_id(rule_id)?;
            crate::loading::load_module_extension_in(repositories.clone(), &label, &rule, &globals)?
        }
    };
    let definition = crate::repository_rule::unpack(&loaded.value)
        .map_err(|error| format!("repository rule {source}: {error}"))?;
    Ok((definition, loaded.functions))
}

/// Replay one record with its loaded definition.
fn replay_one(
    repositories: &Arc<RepositorySet>,
    source_cache: &Path,
    record: &ReplayRecord,
    definition: &crate::repository_rule::RuleDefinition,
    functions: &[starlark::values::OwnedFrozenValue],
) -> Replayed {
    let started = Instant::now();
    marker(&format!(
        "{MARKER_REPLAY_EXEC}{}",
        escape(OsStr::new(&record.canonical))
    ));
    let mut output = None;
    let result = crate::repository_store::replay_local(source_cache, &record.canonical, |stage| {
        let executed = crate::repository_ctx::execute_captured(
            repositories.clone(),
            definition,
            functions,
            &record.attributes,
            &record.canonical,
            &record.original_name,
            &record.definition_label,
            stage,
        )?;
        let inputs =
            crate::host_os::repository_inputs(repositories.host()?.as_ref(), &executed.inputs)?;
        output = Some(executed.output);
        Ok(crate::repository_store::Executed {
            inputs,
            recorded: Vec::new(),
        })
    });
    marker(MARKER_REPLAY_EXEC_END);
    let mismatch = match result {
        Err(error) => Some(format!("replay failed: {error}")),
        Ok(replayed) if replayed.inputs_digest != record.execution.inputs_digest => {
            Some("the identity inputs differ".to_owned())
        }
        Ok(replayed) if replayed.snapshot_digest != record.execution.snapshot_digest => {
            Some("the repository tree differs".to_owned())
        }
        Ok(_) => None,
    };
    let output = output.unwrap_or_default();
    Replayed {
        canonical: record.canonical.clone(),
        definition: record.definition.to_string(),
        flags: record.flags(),
        mismatch,
        output_differs: output != record.output,
        output_bytes: output.len(),
        recorded: record.elapsed,
        wall: started.elapsed(),
    }
}

/// Replay `records` against a repository set pinned to `tables` (one thread
/// per definition, its records in recorded order). Never prints; every
/// failure is a mismatch of its record.
pub fn replay(tables: PinnedTables, context: &CaptureContext, records: &[ReplayRecord]) -> Report {
    replay_until(tables, context, records, &AtomicBool::new(false))
}

/// The mismatch of a record [`replay_until`] skipped.
pub const CANCELLED: &str = "the replay was cancelled";

/// [`replay`], skipping every definition load and execution not started yet
/// once `cancel` is set (a snapshot hit attempt whose validation failed,
/// crate::snapshot::hit: the miss's full analysis need not wait): a skipped
/// record's mismatch is [`CANCELLED`]. An execution in progress completes
/// (its stage is removed as always).
pub fn replay_until(
    tables: PinnedTables,
    context: &CaptureContext,
    records: &[ReplayRecord],
    cancel: &AtomicBool,
) -> Report {
    let started = Instant::now();
    let children_before = children_cpu();
    let pinned_roots = tables.roots.len();
    let pinned_mappings = tables.mappings.len();
    let source_cache = tables.source_cache.clone();
    let repositories = Arc::new(RepositorySet::pinned(
        tables,
        context.options.clone(),
        context.environment.fresh(),
        context.downloads_enabled,
    ));
    let mut groups: Vec<(&DefinitionSource, Vec<&ReplayRecord>)> = Vec::new();
    for record in records {
        match groups
            .iter_mut()
            .find(|(source, _)| **source == record.definition)
        {
            Some((_, members)) => members.push(record),
            None => groups.push((&record.definition, vec![record])),
        }
    }
    let results = Mutex::new(Vec::new());
    std::thread::scope(|scope| {
        for (source, members) in &groups {
            let repositories = &repositories;
            let results = &results;
            let source_cache = &source_cache;
            scope.spawn(move || {
                let cancelled = |record: &ReplayRecord| Replayed {
                    canonical: record.canonical.clone(),
                    definition: source.to_string(),
                    flags: record.flags(),
                    mismatch: Some(CANCELLED.to_owned()),
                    output_differs: false,
                    output_bytes: 0,
                    recorded: record.elapsed,
                    wall: Duration::ZERO,
                };
                if cancel.load(Ordering::Relaxed) {
                    let definition = Definition {
                        source: source.to_string(),
                        records: members.len(),
                        wall: Duration::ZERO,
                        cpu: None,
                        error: Some(CANCELLED.to_owned()),
                    };
                    let replayed = members.iter().map(|record| cancelled(record)).collect();
                    lock(results).push((definition, replayed));
                    return;
                }
                let cpu_before = thread_cpu();
                let loading = Instant::now();
                let loaded = load_definition(repositories, source);
                let mut definition = Definition {
                    source: source.to_string(),
                    records: members.len(),
                    wall: loading.elapsed(),
                    cpu: None,
                    error: None,
                };
                let replayed: Vec<Replayed> = match &loaded {
                    Ok((rule, functions)) => members
                        .iter()
                        .map(|record| {
                            if cancel.load(Ordering::Relaxed) {
                                return cancelled(record);
                            }
                            if rule.identity != record.identity {
                                return Replayed {
                                    canonical: record.canonical.clone(),
                                    definition: source.to_string(),
                                    flags: record.flags(),
                                    mismatch: Some(format!(
                                        "the definition loads as {} (recorded {})",
                                        rule.identity, record.identity
                                    )),
                                    output_differs: false,
                                    output_bytes: 0,
                                    recorded: record.elapsed,
                                    wall: Duration::ZERO,
                                };
                            }
                            replay_one(repositories, source_cache, record, rule, functions)
                        })
                        .collect(),
                    Err(error) => {
                        definition.error = Some(error.clone());
                        members
                            .iter()
                            .map(|record| Replayed {
                                canonical: record.canonical.clone(),
                                definition: source.to_string(),
                                flags: record.flags(),
                                mismatch: Some(format!("the definition did not load: {error}")),
                                output_differs: false,
                                output_bytes: 0,
                                recorded: record.elapsed,
                                wall: Duration::ZERO,
                            })
                            .collect()
                    }
                };
                drop(loaded);
                definition.cpu = thread_cpu()
                    .zip(cpu_before)
                    .map(|(after, before)| after.saturating_sub(before));
                lock(results).push((definition, replayed));
            });
        }
    });
    let mut report = Report {
        pinned_roots,
        pinned_mappings,
        ..Report::default()
    };
    let mut cpu = Some(Duration::ZERO);
    for (definition, replayed) in results.into_inner().unwrap_or_else(PoisonError::into_inner) {
        cpu = cpu
            .zip(definition.cpu)
            .map(|(total, thread)| total + thread);
        report.definitions.push(definition);
        report.replayed.extend(replayed);
    }
    // Recorded order, whatever thread finished first.
    let position: BTreeMap<&str, usize> = records
        .iter()
        .enumerate()
        .map(|(index, record)| (record.canonical.as_str(), index))
        .collect();
    report
        .replayed
        .sort_by_key(|replayed| position.get(replayed.canonical.as_str()).copied());
    report.definitions.sort_by(|a, b| a.source.cmp(&b.source));
    report.cpu = cpu;
    report.children_cpu = children_cpu()
        .zip(children_before)
        .map(|(after, before)| after.saturating_sub(before));
    report.wall = started.elapsed();
    report
}

/// The record mode's dry run over a capture: replay every record of the
/// window (bracketed by the replay markers). `None` without records.
pub fn dry_run(capture: &ReplayCapture) -> Option<Report> {
    let records = capture.records();
    if records.is_empty() {
        return None;
    }
    let context = capture.context()?;
    let tables = capture.tables()?;
    marker(MARKER_REPLAY_BEGIN);
    let report = replay(tables, context, &records);
    marker(MARKER_REPLAY_END);
    Some(report)
}

