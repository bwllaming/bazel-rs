//! Replay of local repository rules (L2-W4R, PLAN-L2 update 1 §(a), §(b)).
//!
//! `local = True` repository rules execute on every run (Bazel refetches
//! local repositories in every batch command and after every server
//! restart); on ~/code 45 of them run in every warm command (rules_java's
//! toolchain configurations and `local_jdk`, the compatibility proxies,
//! bazel_features, the host platform, ...). Their executions are therefore
//! no taint of the analysis snapshot: each becomes a [`ReplayRecord`] — the
//! rule's definition (`repoRuleId`), its bound attributes and names, and the
//! digests of the two runtime parts of its identity, the serialized
//! identity inputs and the encoded tree inventory
//! (crate::repository_store::LocalExecution). A hit re-executes every
//! recorded rule ([`replay`]) in its own stage directory under its stage
//! lock, publishing nothing, and is confirmed only when every replay
//! reproduces both digests: then every identity, hence every root path the
//! saved plan names, is the one a full analysis would publish (the
//! provenance part of the identity is fixed by what the snapshot validates).
//!
//! A replay never resolves the module graph: it runs against a pinned
//! repository set (crate::repository::RepositorySet::pinned) that answers
//! roots, mappings and the "generated by a repository rule" flag from
//! [`PinnedTables`] recorded during the window — exactly the `root()` and
//! `mapping()` results the recorded definition loads and executions
//! consulted (captured while a [`scope`] is open on their thread) — and
//! refuses everything else, which makes the run a miss, never a false hit.
//! Definitions load optimistically from the recorded roots (read-only and
//! silent; a root that a local rule publishes is confirmed by that rule's
//! own replay).
//!
//! Output: a local rule's prints are collected per execution
//! (crate::repository_ctx::execute) and a replay never prints
//! (crate::repository_ctx::execute_captured). v1 of the protocol does not
//! splice live output into the replayed window bytes: a local rule that
//! printed taints the run (`local-repository-output`).
//!
//! In `BAZEL_RS_SNAPSHOT=record` mode the replay runs as a dry run after the
//! window closed ([`dry_run`], crate::snapshot::record): every recorded rule
//! is replayed in parallel (one thread per definition) and compared, with
//! wall and CPU time; a mismatch taints the run
//! (`local-repository-replay-mismatch`).

